using TextAnonymizer.Models;
using TextAnonymizer.ViewModels;

namespace TextAnonymizer.Tests;

public class PreviewViewModelTests
{
    private static (ConversionTable Table, PreviewViewModel Preview, List<bool> Closed) Create(params (string Original, string Replacement)[] pairs)
    {
        var table = new ConversionTable();
        foreach (var (original, replacement) in pairs)
        {
            table.Entries.Add(new ConversionEntry { Original = original, Replacement = replacement });
        }

        var items = table.Entries.Select(e => new PreviewItem(e, e.Replacement, 0, isGenerated: true));
        var preview = new PreviewViewModel("t", "d", items, table);
        var closed = new List<bool>();
        preview.CloseRequested += (_, accepted) => closed.Add(accepted);
        return (table, preview, closed);
    }

    [Fact]
    public void AcceptAll_AppliesEveryLineAndMarksEntriesAutoGenerated()
    {
        var (table, preview, closed) = Create(("Jean", ""), ("Paris", ""));
        preview.Items[0].Replacement = "Paul";
        preview.Items[1].Replacement = "Lyon";

        preview.AcceptAllCommand.Execute(null);

        Assert.Equal(new[] { "Paul", "Lyon" }, table.Entries.Select(e => e.Replacement));
        Assert.All(table.Entries, e => Assert.True(e.IsAutoGenerated));
        Assert.Equal(new[] { true }, closed);
    }

    [Fact]
    public void AcceptSelection_AppliesOnlyCheckedLines()
    {
        var (table, preview, closed) = Create(("Jean", "Paul"), ("Paris", "Lyon"));
        preview.Items[0].Replacement = "Marc";
        preview.Items[1].Replacement = "Nice";
        preview.Items[1].IsSelected = false;

        preview.AcceptSelectionCommand.Execute(null);

        Assert.Equal("Marc", table.Entries[0].Replacement);
        Assert.Equal("Lyon", table.Entries[1].Replacement);
        Assert.Equal(new[] { true }, closed);
    }

    [Fact]
    public void AcceptSelection_WithNothingChecked_ShowsErrorAndStaysOpen()
    {
        var (_, preview, closed) = Create(("Jean", "Paul"));
        preview.Items[0].IsSelected = false;

        preview.AcceptSelectionCommand.Execute(null);

        Assert.True(preview.HasError);
        Assert.Empty(closed);
    }

    [Fact]
    public void Accept_WithDuplicateReplacements_IsRejectedWithMessage()
    {
        var (table, preview, closed) = Create(("Jean", "Paul"), ("Paris", "Lyon"));
        preview.Items[1].Replacement = "Paul";

        preview.AcceptAllCommand.Execute(null);

        Assert.True(preview.HasError);
        Assert.Contains("Paul", preview.ErrorMessage);
        Assert.Equal("Lyon", table.Entries[1].Replacement);
        Assert.Empty(closed);
    }

    [Fact]
    public void Reject_ClosesWithoutChangingTable()
    {
        var (table, preview, closed) = Create(("Jean", "Paul"));
        preview.Items[0].Replacement = "Marc";

        preview.RejectCommand.Execute(null);

        Assert.Equal("Paul", table.Entries[0].Replacement);
        Assert.Equal(new[] { false }, closed);
    }
}
