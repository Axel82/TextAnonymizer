using System.Text;
using TextAnonymizer.Models;
using TextAnonymizer.Services;

namespace TextAnonymizer.Tests;

public sealed class TableStorageServiceTests : IDisposable
{
    private readonly string _directory = Path.Combine(Path.GetTempPath(), "TextAnonymizerTests-" + Guid.NewGuid().ToString("N"));
    private readonly TableStorageService _service;

    public TableStorageServiceTests()
    {
        _service = new TableStorageService(_directory);
    }

    public void Dispose()
    {
        if (Directory.Exists(_directory))
        {
            Directory.Delete(_directory, recursive: true);
        }
    }

    private static ConversionTable SampleTable()
    {
        var table = new ConversionTable { Strategy = MatchingStrategy.IgnoreCaseAndDiacritics };
        table.Entries.Add(new ConversionEntry { Original = "Hélène Confidentielle", Replacement = "Claire Martin", EntityType = EntityType.Nom });
        table.Entries.Add(new ConversionEntry { Original = "Paris", Replacement = "Lyon", EntityType = EntityType.Ville, IsAutoGenerated = true });
        return table;
    }

    [Fact]
    public void SaveThenLoad_RoundTripsTable()
    {
        var path = _service.DefaultPath;

        _service.Save(SampleTable(), path);
        var loaded = _service.Load(path);

        Assert.Equal(MatchingStrategy.IgnoreCaseAndDiacritics, loaded.Strategy);
        Assert.Equal(2, loaded.Entries.Count);
        Assert.Equal("Hélène Confidentielle", loaded.Entries[0].Original);
        Assert.Equal("Claire Martin", loaded.Entries[0].Replacement);
        Assert.Equal(EntityType.Ville, loaded.Entries[1].EntityType);
        Assert.True(loaded.Entries[1].IsAutoGenerated);
        Assert.False(loaded.Entries[0].IsAutoGenerated);
    }

    [Fact]
    public void SavedFile_IsNotReadableInClear()
    {
        _service.Save(SampleTable(), _service.DefaultPath);

        var bytes = File.ReadAllBytes(_service.DefaultPath);
        var asUtf8 = Encoding.UTF8.GetString(bytes);

        Assert.DoesNotContain("Confidentielle", asUtf8);
        Assert.DoesNotContain("Claire", asUtf8);
        Assert.DoesNotContain("Original", asUtf8);
        Assert.NotEqual((byte)'{', bytes[0]);
    }

    [Fact]
    public void SavedKey_IsNotStoredInClear()
    {
        _service.Save(SampleTable(), _service.DefaultPath);

        Assert.True(File.Exists(Path.Combine(_directory, "table.key")));
    }

    [Fact]
    public void Save_TwiceProducesDifferentCiphertext()
    {
        var table = SampleTable();
        var first = Path.Combine(_directory, "a.enc");
        var second = Path.Combine(_directory, "b.enc");

        _service.Save(table, first);
        _service.Save(table, second);

        Assert.NotEqual(File.ReadAllBytes(first), File.ReadAllBytes(second));
    }

    [Fact]
    public void Load_TamperedFile_ThrowsExplicitError()
    {
        _service.Save(SampleTable(), _service.DefaultPath);
        var bytes = File.ReadAllBytes(_service.DefaultPath);
        bytes[^1] ^= 0xFF;
        File.WriteAllBytes(_service.DefaultPath, bytes);

        var ex = Assert.Throws<TableStorageException>(() => _service.Load(_service.DefaultPath));

        Assert.Contains("déchiffrer", ex.Message);
    }

    [Fact]
    public void Load_PlainJson_IsRejected()
    {
        Directory.CreateDirectory(_directory);
        var path = Path.Combine(_directory, "plain.json");
        File.WriteAllText(path, "{\"Entries\":[]} and some padding to exceed the header size");

        Assert.Throws<TableStorageException>(() => _service.Load(path));
    }

    [Fact]
    public void Load_MissingFile_ThrowsExplicitError()
    {
        Assert.Throws<TableStorageException>(() => _service.Load(Path.Combine(_directory, "absent.enc")));
    }

    [Fact]
    public void ExportThenImport_UsesReadableJson()
    {
        var path = Path.Combine(_directory, "export.json");

        _service.Export(SampleTable(), path);
        var json = File.ReadAllText(path);
        var imported = _service.Import(path);

        Assert.Contains("Hélène Confidentielle", json);
        Assert.Contains("\"Ville\"", json);
        Assert.Equal(2, imported.Entries.Count);
        Assert.Equal(MatchingStrategy.IgnoreCaseAndDiacritics, imported.Strategy);
    }

    [Fact]
    public void Import_InvalidJson_ThrowsExplicitError()
    {
        Directory.CreateDirectory(_directory);
        var path = Path.Combine(_directory, "bad.json");
        File.WriteAllText(path, "not json");

        Assert.Throws<TableStorageException>(() => _service.Import(path));
    }
}
