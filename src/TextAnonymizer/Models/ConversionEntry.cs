using CommunityToolkit.Mvvm.ComponentModel;

namespace TextAnonymizer.Models;

/// <summary>Une ligne de la table de conversion : mot original ↔ remplaçant.</summary>
public sealed partial class ConversionEntry : ObservableObject
{
    [ObservableProperty]
    private string _original = string.Empty;

    [ObservableProperty]
    private string _replacement = string.Empty;

    [ObservableProperty]
    private EntityType _entityType = EntityType.Autre;

    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(StatusLabel))]
    private bool _isAutoGenerated;

    public string StatusLabel => IsAutoGenerated ? "Auto-généré" : "Manuel";
}
