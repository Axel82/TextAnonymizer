using System.Collections.ObjectModel;
using CommunityToolkit.Mvvm.ComponentModel;
using CommunityToolkit.Mvvm.Input;
using TextAnonymizer.Models;

namespace TextAnonymizer.ViewModels;

/// <summary>Ligne de l'aperçu : remplacement proposé pour une entrée, modifiable avant validation.</summary>
public sealed partial class PreviewItem : ObservableObject
{
    public PreviewItem(ConversionEntry entry, string replacement, int occurrences, bool isGenerated)
    {
        Entry = entry;
        _replacement = replacement;
        Occurrences = occurrences;
        IsGenerated = isGenerated;
    }

    public ConversionEntry Entry { get; }

    public string Original => Entry.Original;

    public EntityType EntityType => Entry.EntityType;

    /// <summary>Nombre d'occurrences de l'original dans le texte source.</summary>
    public int Occurrences { get; }

    /// <summary>La valeur initiale a été proposée par le générateur (et non saisie par l'utilisateur).</summary>
    public bool IsGenerated { get; }

    [ObservableProperty]
    private string _replacement;

    /// <summary>Ligne retenue par « Valider la sélection ».</summary>
    [ObservableProperty]
    private bool _isSelected = true;
}

/// <summary>Liste modifiable des remplacements proposés, à valider (en entier ou en partie) ou à rejeter.</summary>
public sealed partial class PreviewViewModel : ObservableObject
{
    private readonly ConversionTable _table;

    public PreviewViewModel(string title, string description, IEnumerable<PreviewItem> items, ConversionTable table)
    {
        Title = title;
        Description = description;
        _table = table;
        Items = new ObservableCollection<PreviewItem>(items);
    }

    public string Title { get; }

    public string Description { get; }

    public ObservableCollection<PreviewItem> Items { get; }

    /// <summary>Levé pour fermer la fenêtre ; le paramètre vaut <c>true</c> si l'aperçu est validé.</summary>
    public event EventHandler<bool>? CloseRequested;

    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(HasError))]
    private string? _errorMessage;

    public bool HasError => !string.IsNullOrEmpty(ErrorMessage);

    /// <summary>Valide la bijection de la table telle qu'elle serait après application des lignes <paramref name="applied"/>.</summary>
    public BijectionResult Validate(IReadOnlyCollection<PreviewItem>? applied = null)
    {
        var overrides = (applied ?? Items).ToDictionary(i => i.Entry, i => i.Replacement);
        return BijectionValidator.Validate(
            _table.Entries.Select(e => (e.Original, overrides.GetValueOrDefault(e, e.Replacement))),
            _table.Strategy);
    }

    [RelayCommand]
    private void AcceptAll() => Accept(Items.ToList());

    [RelayCommand]
    private void AcceptSelection()
    {
        var selected = Items.Where(i => i.IsSelected).ToList();
        if (selected.Count == 0)
        {
            ErrorMessage = "Aucune ligne sélectionnée : cochez au moins un remplacement, ou choisissez « Tout valider ».";
            return;
        }

        Accept(selected);
    }

    [RelayCommand]
    private void Reject() => CloseRequested?.Invoke(this, false);

    private void Accept(IReadOnlyCollection<PreviewItem> applied)
    {
        var result = Validate(applied);
        if (!result.IsValid)
        {
            ErrorMessage = result.Message;
            return;
        }

        ErrorMessage = null;
        foreach (var item in applied)
        {
            if (item.Entry.Replacement != item.Replacement)
            {
                item.Entry.Replacement = item.Replacement;
                item.Entry.IsAutoGenerated = item.IsGenerated;
            }
        }

        CloseRequested?.Invoke(this, true);
    }
}
